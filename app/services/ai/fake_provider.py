"""A provider that answers from a template instead of from a network.

This is what makes the whole feature runnable, and testable, with no API key and
no internet. It is deterministic: the same spec always produces the same
questions, so a test can assert on them.

It can also fail on purpose. ``AI_FAKE_MODE`` selects between a good answer, an
answer that is well-formed but wrong about the request, and a provider that is
simply down — which is how the two 503 paths get exercised end to end.
"""

from itertools import cycle, islice

from app.core.config import FakeMode, get_settings
from app.core.exceptions import AIUnavailableError
from app.models import InterviewLevel, QuestionCategory, QuestionDifficulty
from app.services.ai.base import AIProvider
from app.services.ai.prompt_loader import QUESTION_GENERATION
from app.services.ai.schemas import GeneratedQuestion, GeneratedQuestionSet, QuestionSpec

#: Recorded in questions.model_name, so a row generated by the fake is obvious.
MODEL_NAME = "fake-1"

#: A skill nobody can have requested: a request bounds skills to 60 characters,
#: but more importantly this string is not a technology.
_UNREQUESTED_SKILL = "Telepati"

_DIFFICULTY_BY_LEVEL: dict[InterviewLevel, QuestionDifficulty] = {
    InterviewLevel.JUNIOR: QuestionDifficulty.EASY,
    InterviewLevel.MID: QuestionDifficulty.MEDIUM,
    InterviewLevel.SENIOR: QuestionDifficulty.HARD,
    InterviewLevel.LEAD: QuestionDifficulty.HARD,
}

_CATEGORIES = (
    QuestionCategory.TECHNICAL,
    QuestionCategory.BEHAVIORAL,
    QuestionCategory.SITUATIONAL,
    QuestionCategory.SYSTEM_DESIGN,
)


class FakeProvider(AIProvider):
    """Deterministic provider for development and tests."""

    name = "fake"

    def __init__(self, mode: FakeMode | None = None) -> None:
        """Use ``mode``, or whatever ``AI_FAKE_MODE`` says when it is omitted."""
        self._mode: FakeMode = mode if mode is not None else get_settings().ai_fake_mode

    async def generate_questions(
        self,
        spec: QuestionSpec,
        *,
        feedback: str | None = None,
    ) -> GeneratedQuestionSet:
        """Return canned questions, or fail in whichever way the mode selects.

        ``feedback`` is accepted and ignored: in ``invalid`` mode the corrective
        retry has to fail too, or the failure path would never be reachable.
        """
        if self._mode == "unavailable":
            raise AIUnavailableError

        # One extra question, and one of them about a skill nobody asked for:
        # well-formed JSON that still cannot be stored.
        count = spec.count + 1 if self._mode == "invalid" else spec.count
        skills = list(islice(cycle(spec.skills), count))
        if self._mode == "invalid":
            skills[-1] = _UNREQUESTED_SKILL

        difficulty = _DIFFICULTY_BY_LEVEL[spec.level]
        questions = tuple(
            GeneratedQuestion(
                content=(
                    f"Ceritakan pengalamanmu memakai {skill} pada posisi {spec.position}, "
                    f"dan satu kendala teknis yang pernah kamu temui di sana. "
                    f"(pertanyaan {index})"
                ),
                category=_CATEGORIES[(index - 1) % len(_CATEGORIES)],
                skill=skill,
                difficulty=difficulty,
            )
            for index, skill in enumerate(skills, start=1)
        )

        return GeneratedQuestionSet(
            questions=questions,
            model_name=MODEL_NAME,
            prompt_version=QUESTION_GENERATION.version,
        )
