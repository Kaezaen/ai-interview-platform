"""Declarative base and the column mixins every table shares.

The metadata carries an explicit naming convention so that indexes and
constraints get deterministic names instead of whatever the database happens to
invent. A later migration can then reference ``uq_users_email`` by name rather
than guessing at it, which is exactly what dropping or altering a constraint
requires.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

#: ``column_0_N_name`` expands to every column in the constraint, so composite
#: indexes are named after all of their columns rather than just the first.
NAMING_CONVENTION: dict[str, str] = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Base class for every ORM model."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UUIDPrimaryKeyMixin:
    """A UUID primary key generated by the application, not the database.

    Generating the id in Python means a service knows the identifier before the
    row is flushed, which keeps multi-step writes from needing a round trip just
    to learn what they created.
    """

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        # Mixin columns are appended last by default; these keep the primary key
        # first and the timestamps last in the generated DDL, so "\d users" reads
        # the way the table is actually thought about.
        sort_order=-100,
    )


class TimestampMixin:
    """Timezone-aware creation and modification timestamps.

    Both defaults are set by the database so that a row written outside the ORM
    — a migration, or psql — still gets correct values.
    """

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        sort_order=100,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
        sort_order=101,
    )
